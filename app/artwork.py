"""
artwork.py - read the image manifest (cover art/artist photos) for templates to use

Image files are generated by tools/fetch_artwork.py
    app/static/img/cover_<SongID>.jpg
    app/static/img/artist_<ArtistID>.jpg
    app/static/img/manifest.json

Why use a manifest instead of adding a DB column: to keep the schema aligned with the team's ER diagram.
Templates call cover_url(song_id) / artist_photo_url(artist_id)
If an image is missing, it returns None and the macro falls back to a gradient + initials
"""
from __future__ import annotations

import json
import pathlib

from flask import current_app, url_for

# one cache per process — check mtime to pick up new files after running fetch_artwork
_state: dict = {"mtime": None, "data": {"covers": {}, "artists": {}}}
_EMPTY = {"covers": {}, "artists": {}}


def _manifest_path() -> pathlib.Path:
    return pathlib.Path(current_app.static_folder) / "img" / "manifest.json"


def _load() -> dict:
    path = _manifest_path()
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return _EMPTY

    if _state["mtime"] != mtime:
        try:
            _state["data"] = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            _state["data"] = _EMPTY
        _state["mtime"] = mtime

    return _state["data"]


def _versioned_url(name: str) -> str:
    """Static URL with ?v=<mtime>, so a replaced file is not served from browser cache."""
    path = pathlib.Path(current_app.static_folder) / "img" / name
    try:
        version = int(path.stat().st_mtime)
    except OSError:
        version = 0
    return url_for("static", filename=f"img/{name}", v=version)


def cover_url(song_id) -> str | None:
    name = _load().get("covers", {}).get(str(song_id))
    return _versioned_url(name) if name else None


def artist_photo_url(artist_id) -> str | None:
    name = _load().get("artists", {}).get(str(artist_id))
    return _versioned_url(name) if name else None
